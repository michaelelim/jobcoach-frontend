function toggleTheme() {
  const dark = !document.documentElement.getAttribute('data-theme') === 'dark';
  document.documentElement.setAttribute('data-theme', dark ? 'dark' : '');
  $('themeToggle').textContent = dark ? '☀️' : '🌙';
  localStorage.setItem('theme', dark ? 'dark' : 'light');
}
$('themeToggle').addEventListener('click', toggleTheme);

if (localStorage.getItem('theme') === 'dark') {
  document.documentElement.setAttribute('data-theme', 'dark');
  $('themeToggle').textContent = '☀️';
}

// ── Search/filter state ──────────────────────────────────
let activeFilter = 'all';
let searchTerm = '';

function renderCards() {
  const q = searchTerm.toLowerCase();
  const filtered = RESOURCES.filter(r => {
    const matchCat = activeFilter === 'all' || r.cat === activeFilter;
    const matchQ = !q || r.category.toLowerCase().includes(q) || r.title.toLowerCase().includes(q) || r.short.toLowerCase().includes(q);
    return matchCat && matchQ;
  });

  main.innerHTML = `
    <header class="hero"><div class="container"><h1>Your <span class="accent">Career Development Hub</span></h1>
    <p>Resources to help you navigate your job search, build your career, and reach your goals.</p></div></header>
    <section class="filters"><div class="container">
      <div class="search-bar"><span class="search-icon">🔍</span><input type="text" id="searchInput" placeholder="Search all resources…" value="${searchTerm}"></div>
      <div class="filter-btn ${activeFilter==='all'?'active':''}" data-f="all">All</div>
      ${['resume','cover-letter','job-search','networking','linkedin','interview','job-market','gov','prof-dev']
        .map(f => `<button class="filter-btn ${activeFilter===f?'active':''}" data-f="${f}">${RESOURCES.find(r=>r.cat===f)?.category || f}</button>`).join('')}
    </div></section>
    <section class="container">${filtered.length === 0 ? '<p style="text-align:center;padding:40px;color:var(--text2)">No resources found.</p>' : `<div class="featured-grid">${filtered.map(r => `
      <div class="card cat-${r.cat}" onclick="showArticle(${r.id})">
        <div class="card-header"><div class="cat-icon">${r.icon}</div>
        <div class="cat-tag">${r.category}</div><h3 class="card-title">${r.title}</h3></div>
        <div class="card-body"><p class="card-desc">${r.short}</p></div>
        <div class="card-footer"><span>Read Guide</span><span class="arrow">→</span></div>
      </div>`).join('')}</div>`}</div></section>`;

  $('searchInput').addEventListener('input', e => {
    searchTerm = e.target.value;
    renderCards();
  });
  main.querySelectorAll('.filter-btn').forEach(btn => {
    btn.addEventListener('click', () => { activeFilter = btn.dataset.f; renderCards(); });
  });
}

// ── Article view ──────────────────────────────────────────
